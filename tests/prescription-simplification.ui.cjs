const assert = require('node:assert/strict');
const puppeteer = require('puppeteer-core');
const { writeFileSync, mkdirSync } = require('node:fs');
const base = process.env.TEST_BASE, cid = 'finance_isolated_test';
const en = process.env.TEST_LANG === 'en', lang = en ? 'en' : 'ar';
const artifacts = process.env.TEST_ARTIFACT_DIR || '/tmp/coredent-prescription-proof';
mkdirSync(artifacts, {recursive:true});
const wait = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const login = await fetch(base + '/api/auth/clinic-login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'finance-isolated@example.invalid', password: 'test-only-password', role: 'manager' }) }).then(r => r.json());
  assert(login.token);
  const db = async (action, path, id, data) => {
    const r = await fetch(base + '/api/db', { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + login.token }, body: JSON.stringify({ action, path, id, data }) });
    const out = await r.json(); assert.equal(r.status, 200, JSON.stringify(out)); return out;
  };
  await db('setDoc', `clinics/${cid}/patients`, 'rx_patient', { name: en ? 'Prescription Test Patient' : 'مريض اختبار الروشتة', phone: '01000000000', age: '35', createdAt: new Date().toISOString() });
  const category = en ? 'Clinic medications' : 'أدوية العيادة';
  await db('setDoc', `clinics/${cid}/custom_categories`, 'rx_category', { name: category });
  for (const [id, name] of [['rx1', 'Augmentin 1g'], ['rx2', 'Cataflam 50mg'], ['rx3', 'Orovex Mouthwash']]) await db('setDoc', `clinics/${cid}/custom_medications`, id, { name, category, dose: en ? '1 Tablet' : 'قرص واحد', frequency: en ? 'Every 12 hours (after meals)' : 'كل 12 ساعة (بعد الأكل)', duration: en ? '5 Days' : '5 أيام' });
  const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  const page = await browser.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.setViewport({ width: 1440, height: 1050 });
  await page.evaluateOnNewDocument((token, clinic, language) => {
    localStorage.setItem('dental_auth_token', token);
    localStorage.setItem('dental_saas_session', JSON.stringify({ type: 'clinic', clinicId: clinic.id, clinicName: clinic.name }));
    localStorage.setItem('i18nextLng', language);
    localStorage.setItem('auto_backup_last_date_' + clinic.id, new Date().toISOString().slice(0, 10));
  }, login.token, login.clinic, lang);
  const click = async (text, exact = false) => assert(await page.evaluate((t, x) => { const b = [...document.querySelectorAll('button')].find(b => b.getClientRects().length && (x ? b.textContent.trim() === t : b.textContent.includes(t))); b?.click(); return !!b; }, text, exact), 'Missing button: ' + text);
  const fill = async (sel, value) => { await page.click(sel); await page.keyboard.down('Control'); await page.keyboard.press('A'); await page.keyboard.up('Control'); await page.keyboard.press('Backspace'); await page.type(sel, value); };
  const rows = () => page.$$('[data-testid="rx-medication-row"]');
  const open = async () => { await click(en ? 'Prescriptions' : 'الروشتة العلاجية', true); await page.waitForSelector('[data-testid="pharmacy-drug"]'); };
  try {
    await page.goto(base, { waitUntil: 'networkidle2' }); await open();
    assert.equal((await page.$$('[data-testid="pharmacy-drug"]')).length, 3, 'DB catalog rendered');
    assert.equal(await page.$('input[placeholder="e.g., Augmentin 1g"],input[placeholder="مثال: Augmentin 1g"]'), null, 'custom form initially collapsed');
    await page.click('[data-testid="pharmacy-drug"]');
    await page.waitForSelector('[data-testid="rx-medication-row"]');
    assert.equal((await rows()).length, 1, 'one-tap add');
    assert.equal(await page.$eval('[data-testid="pharmacy-drug"]', e => e.getAttribute('aria-pressed')), 'true');
    await page.click('[data-testid="pharmacy-drug"]'); await wait(100);
    assert.equal((await rows()).length, 0, 'second tap removes');
    await page.click('[data-testid="pharmacy-drug"]');
    await page.evaluate(() => document.querySelectorAll('[data-testid="pharmacy-drug"]')[1].click());
    assert.equal((await rows()).length, 2);
    await page.click(en ? 'button[title="Edit item"]' : 'button[title="تعديل هذا البند"]');
    const nameInput = en ? 'input[placeholder="e.g., Augmentin 1g"]' : 'input[placeholder="مثال: Augmentin 1g"]';
    await page.waitForSelector(nameInput);
    assert(await page.$eval(nameInput, el => !!el.closest('[data-testid="rx-medication-row"]')), 'editor is inline');
    await click(en ? '7 Days' : '7 أيام', true);
    await page.screenshot({path: `${artifacts}/rx-${lang}-inline.png`, fullPage: true});
    await click(en ? 'Save Changes' : 'حفظ تعديلات البند', true);
    assert((await page.$eval('[data-testid="rx-medication-row"]', e => e.textContent)).includes(en ? '7 Days' : '7 أيام'));
    // Reordering remains available.
    await page.click(en ? 'button[title="Move Down"]' : 'button[title="نقل لأسفل"]');
    assert((await page.$eval('[data-testid="rx-medication-row"]', e => e.textContent)).includes('Cataflam'));
    await page.screenshot({ path: `${artifacts}/rx-${lang}-one-tap.png`, fullPage: true });
    await page.click('[data-testid="custom-drug-toggle"]'); await fill(nameInput, 'Custom DB Test');
    await click(en ? 'Add to Prescription' : 'إدراج بالروشتة الطبية', true);
    assert.equal((await rows()).length, 3);
    await page.click(en ? 'button[title="Toggle recommendations on the prescription"]' : 'button[title="تفعيل أو قفل التوصيات في الروشتة"]');
    await page.waitForSelector('textarea'); await fill('textarea', en ? 'Test patient advice' : 'توصيات المريض للاختبار');
    await page.click('[data-testid="print-style-toggle"]');
    await click(en ? 'Custom Pad' : 'تصميمي الخاص');
    await page.waitForSelector('[data-testid="pad-editor-modal"]');
    const imageData = await page.evaluate(() => {const c=document.createElement('canvas');c.width=420;c.height=594;const x=c.getContext('2d');x.fillStyle='#ffffff';x.fillRect(0,0,420,594);x.fillStyle='#0e7490';x.fillRect(0,0,420,78);x.fillStyle='#ffffff';x.font='bold 20px sans-serif';x.fillText('TEST CLINIC',120,45);x.fillStyle='#94a3b8';x.fillRect(30,90,150,4);x.fillRect(30,565,360,3);return c.toDataURL('image/png').split(',')[1];});
    const fixturePath=artifacts+'/rx-test-pad.png';writeFileSync(fixturePath,Buffer.from(imageData,'base64'));
    await (await page.$('[data-testid="pad-editor-modal"] input[type="file"]')).uploadFile(fixturePath);
    await page.waitForSelector('[data-testid="pad-paper"] img');
    await page.waitForFunction(()=>document.querySelector('[data-testid="pad-paper"] img')?.naturalWidth>0);
    await page.waitForFunction(()=>!document.body.innerText.includes('Uploading...')&&!document.body.innerText.includes('جاري الرفع...'));
    const font = en ? 'input[aria-label="Font size"]' : 'input[aria-label="حجم الخط"]';
    assert.equal((await page.$$(font)).length, 1, 'single font-size slider');
    const field = '[data-testid="pad-field-date"]';
    await page.focus(field); await page.keyboard.press('ArrowDown'); await page.keyboard.down('Shift'); await page.keyboard.press('ArrowLeft'); await page.keyboard.up('Shift');
    const before = await page.$eval(field, e => ({ top: parseFloat(e.style.top), left: parseFloat(e.style.left) }));
    const paperRect = await page.$eval('[data-testid="pad-paper"]', e => {const r=e.getBoundingClientRect();return {x:r.x,y:r.y,width:r.width,height:r.height};});
    const rect = await page.$eval(field, e => { const r = e.getBoundingClientRect(); return { x: r.x + 15, y: r.y + 10 }; });
    await page.mouse.move(rect.x, rect.y); await page.mouse.down(); await page.mouse.move(paperRect.x + paperRect.width * .5 + 15, rect.y + 45, { steps: 5 });
    await page.waitForSelector('[data-testid="pad-guide-v"]');
    await page.screenshot({ path: `${artifacts}/rx-${lang}-drag.png` }); await page.mouse.up();
    const after = await page.$eval(field, e => ({ top: parseFloat(e.style.top), left: parseFloat(e.style.left) }));
    assert(after.top > before.top && after.left < before.left, 'drag changes correct field position');
    await page.$eval(font, e => { const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set; set.call(e, '18'); e.dispatchEvent(new Event('input', { bubbles: true })); e.dispatchEvent(new Event('change', { bubbles: true })); });
    await wait(850);
    await page.screenshot({ path: `${artifacts}/rx-${lang}-popup.png` });
    assert(await page.$eval('[data-testid="pad-paper"]', p => {const r = p.getBoundingClientRect(); return [...p.querySelectorAll('[data-testid^="pad-field-"]')].every(e=>{const b=e.getBoundingClientRect();return b.left >= r.left-1 && b.right <= r.right+1 && b.top >= r.top-1 && b.bottom <= r.bottom+1;});}), 'fields stay inside paper');
    const savedClinic = await db('getDoc', 'clinics', cid);
    assert.equal(savedClinic.customPrescriptionPadConfig.date.top, after.top, 'pad position autosaved to database');
    assert.equal(savedClinic.customPrescriptionPadConfig.date.fontSize, 18);
    assert(savedClinic.customPrescriptionPadConfig.backgroundImage, 'uploaded image persisted');
    // Resize remains available via the corner handle, without extra position-panel sliders.
    await page.focus('[data-testid="pad-field-medicationsBox"]');
    const resize = await page.$eval('[aria-label="' + (en ? 'Resize box' : 'تغيير حجم المربع') + '"]', e=>{const r=e.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2};});
    await page.mouse.move(resize.x,resize.y);await page.mouse.down();await page.mouse.move(resize.x-20,resize.y-20,{steps:4});await page.mouse.up();
    await wait(800);
    await page.click('[data-testid="pad-editor-modal"] button[aria-pressed]');
    await wait(800);
    assert.equal((await db('getDoc','clinics',cid)).customPrescriptionPadConfig.hideBackgroundOnPrint,false, 'print background toggle saved');
    await page.keyboard.press('Escape'); await page.waitForFunction(() => !document.querySelector('[data-testid="pad-editor-modal"]'));
    // Save and print uses unchanged print generator; intercept the hidden print frame content.
    await click(en ? 'Save & Print' : 'حفظ وطباعة', true);
    await page.waitForSelector('iframe'); await wait(300);
    const print = await page.$eval('iframe', e => e.contentDocument.documentElement.outerHTML);
    assert(print.includes('Custom DB Test') && print.includes(en ? 'Test patient advice' : 'توصيات المريض للاختبار'), 'generated print contains medications and advice');
    await wait(1800);
    const prescriptions = await db('getDocs', `clinics/${cid}/prescriptions`);
    assert(prescriptions.length >= 1); const rx = prescriptions[prescriptions.length - 1];
    const rxData = rx.data || rx;
    assert.equal(rxData.prescriptionStyle, 'custom_pad', 'autosave does not reset selected print style');
    assert.equal(rxData.medications.length, 3, 'prescription saved with all medications');
    await page.setViewport({width:390,height:844});
    await page.screenshot({path:`${artifacts}/rx-${lang}-mobile.png`,fullPage:true});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'no mobile horizontal page overflow');
    await page.setViewport({width:1440,height:1050});
    await click(en ? 'Save without printing' : 'حفظ بدون طباعة', true); await wait(500);
    const all = await db('getDocs', `clinics/${cid}/prescriptions`); assert.equal(all.length, prescriptions.length + 1, 'save-only persisted');
    // Reset and remove-image actions stay available in the popup and persist too.
    await page.reload({waitUntil:'networkidle2'});
    await open(); await wait(200); if(await page.$eval('[data-testid="print-style-toggle"]',e=>e.getAttribute('aria-expanded'))==='false')await page.click('[data-testid="print-style-toggle"]');await wait(100);await click(en ? 'Custom Pad' : 'تصميمي الخاص');
    await page.waitForSelector('[data-testid="pad-editor-modal"]');
    await page.click(en ? 'button[title="Reset positions"]' : 'button[title="إعادة ضبط المواضع"]');
    await page.click('[data-testid="pad-paper"] button');
    await page.waitForFunction(()=>!document.querySelector('[data-testid="pad-paper"] img'));
    await wait(850);const reset=await db('getDoc','clinics',cid);
    assert.equal(reset.customPrescriptionPadConfig.backgroundImage,'');
    assert.notEqual(reset.customPrescriptionPadConfig.date.top,after.top);
    await page.keyboard.press('Escape');
    assert.deepEqual(errors, []);
    console.log('PASS prescriptions ' + lang + ': DB catalog, one-tap toggle, inline edit, reorder, custom drug, advice, modal, single slider, arrows+Shift, drag, DB autosave, print and save-only');
  } catch (e) { await page.screenshot({ path: `${artifacts}/rx-${lang}-failure.png`, fullPage: true }); console.error(await page.$eval('body', e => e.innerText)); throw e; }
  finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
