import assert from 'node:assert/strict';
import { getClinicPaymentMethods, normalizePaymentMethod, paymentMethodForReport, paymentMethodMapAmount, paymentMethodHistoryHasAmount, paymentMethodLabel } from '../src/utils/paymentMethods';
assert.deepEqual(getClinicPaymentMethods([]), []);
assert.equal(getClinicPaymentMethods(undefined).length,4);
assert.deepEqual(getClinicPaymentMethods([' Cash ','cash','اتصالات كاش','فودافون كاش','Mastercard']),['كاش','اتصالات كاش','فودافون كاش','Mastercard']);
for(const name of ['اتصالات كاش','فودافون كاش','Vodafone Cash','Mastercard','constructor','__proto__']) assert.equal(normalizePaymentMethod(name),name);
assert.equal(normalizePaymentMethod('Insta Pay'),'إنستاباي');
assert.equal(normalizePaymentMethod('Wallet'),'محفظة');
assert.equal(paymentMethodLabel('محفظة',true),'E-Wallet');
assert.equal(paymentMethodLabel('اتصالات كاش',true),'اتصالات كاش');
assert.equal(paymentMethodForReport('fast wallet',['FAST WALLET']),'FAST WALLET');
assert.equal(paymentMethodMapAmount({'Fast Wallet':.01,'FAST WALLET':.02},'fast wallet'),.03);
assert(paymentMethodHistoryHasAmount([{paymentMethod:'Fast Wallet',amount:.01},{paymentMethod:'Fast Wallet',amount:-.01}],'FAST WALLET'));
assert(paymentMethodHistoryHasAmount({payments:[{paymentMethod:'اتصالات كاش',amount:.01}]},'اتصالات كاش'));
assert(!paymentMethodHistoryHasAmount({payments:[{paymentMethod:'اتصالات كاش',amount:100}]},'cash'));
assert(!paymentMethodHistoryHasAmount({paymentMethod:'اتصالات كاش',cost:100,paidAmount:0},'اتصالات كاش'));
assert(paymentMethodHistoryHasAmount({dynamicRevenues:{'اتصالات كاش':.01}},'اتصالات كاش'));
assert(paymentMethodHistoryHasAmount({cashRevenue:.01},'cash'));
assert(paymentMethodHistoryHasAmount({paymentMethod:'visa',status:'paid',grandTotal:.01},'فيزا'));
console.log('PASS exact aliases, custom cash/card names, empty/default settings, bilingual labels, historical cents, case-preserving report identity and immutable map aliases.');
